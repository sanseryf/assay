"""Report formats besides the terminal: shareable HTML and SARIF for code scanning."""

from __future__ import annotations

import html
import json
from typing import Any

from . import __version__
from .models import Group, Report, Severity

_SARIF_LEVEL = {
    Severity.ERROR: "error",
    Severity.WARNING: "warning",
    Severity.INFO: "note",
}


def to_html(report: Report) -> str:
    """A standalone, escaped HTML report; no scripts, no external assets."""
    rows = "\n".join(_html_group(index, group) for index, group in enumerate(report.groups, 1))
    empty = '<p class="clean">No problems found.</p>' if not report.groups else ""
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Assay report</title>
<style>
:root {{ color-scheme: light dark; }}
body {{ font: 15px/1.5 system-ui, sans-serif; margin: 2rem auto; max-width: 70rem; padding: 0 1rem; }}
h1 {{ font-size: 1.4rem; }}
.summary {{ color: #555; }}
.group {{ border: 1px solid #ccc; border-radius: 8px; padding: 1rem; margin: 1rem 0; }}
.group h2 {{ font-size: 1rem; margin: 0 0 .25rem; }}
.layer {{ font-size: .8rem; text-transform: uppercase; letter-spacing: .05em; color: #666; }}
.path {{ font-family: ui-monospace, monospace; }}
.hint {{ color: #555; }}
.samples {{ font-family: ui-monospace, monospace; color: #444; }}
.clean {{ color: #2e7d32; }}
footer {{ margin-top: 2rem; color: #666; font-size: .85rem; }}
</style>
</head>
<body>
<h1>Assay report</h1>
<p class="summary">{html.escape(_summary(report))}</p>
{empty}
{rows}
<footer>Generated by Assay {html.escape(__version__)}{" · redacted" if report.redacted else ""}</footer>
</body>
</html>
"""


def _summary(report: Report) -> str:
    return (
        f"{report.payloads_scanned:,} payloads · {report.payloads_clean:,} clean · "
        f"{report.payloads_failed:,} with findings · {report.findings_total:,} findings · "
        f"{report.duration_ms:,} ms"
    )


def _html_group(index: int, group: Group) -> str:
    samples = (
        f'<p class="samples">e.g. {html.escape(", ".join(group.sample_values))}</p>'
        if group.sample_values
        else ""
    )
    hint = f'<p class="hint">{html.escape(group.hint)}</p>' if group.hint else ""
    return f"""<section class="group">
<h2>#{index} <span class="path">{html.escape(group.path)}</span></h2>
<p class="layer">{html.escape(group.layer.value)} · {html.escape(group.severity.value)} · {group.payloads_affected:,} records</p>
<p>{html.escape(group.message)}</p>
{samples}
{hint}
</section>"""


def to_sarif(report: Report) -> str:
    """SARIF 2.1.0, one result per group with its representative location."""
    rules: dict[str, dict[str, Any]] = {}
    results: list[dict[str, Any]] = []
    for group in report.groups:
        rules.setdefault(
            group.fingerprint,
            {
                "id": group.fingerprint,
                "name": group.rule,
                "shortDescription": {"text": group.message},
                "fullDescription": {"text": group.hint or group.message},
                "defaultConfiguration": {"level": _SARIF_LEVEL[group.severity]},
                "properties": {"layer": group.layer.value, "path": group.path},
            },
        )
        results.append(_sarif_result(group))

    document = {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [
            {
                "tool": {
                    "driver": {
                        "name": "Assay",
                        "informationUri": "https://github.com/sanseryf/assay",
                        "version": __version__,
                        "rules": list(rules.values()),
                    }
                },
                "results": results,
            }
        ],
    }
    return json.dumps(document, indent=2, ensure_ascii=False)


def _sarif_result(group: Group) -> dict[str, Any]:
    sample = group.findings[0] if group.findings else None
    payload_id = sample.payload_id if sample is not None else ""
    line = sample.line if sample is not None and sample.line is not None else 1
    column = sample.col if sample is not None and sample.col is not None else 1
    return {
        "ruleId": group.fingerprint,
        "level": _SARIF_LEVEL[group.severity],
        "message": {"text": _sarif_message(group)},
        "locations": [
            {
                "physicalLocation": {
                    "artifactLocation": {"uri": payload_id.replace("\\", "/") or "payload"},
                    "region": {"startLine": line, "startColumn": column},
                },
                "logicalLocations": [{"fullyQualifiedName": group.path, "kind": "member"}],
            }
        ],
        "properties": {
            "layer": group.layer.value,
            "payloadsAffected": group.payloads_affected,
            "findings": group.count,
        },
    }


def _sarif_message(group: Group) -> str:
    text = group.message
    if group.hint:
        text = f"{text}. {group.hint}"
    return text
